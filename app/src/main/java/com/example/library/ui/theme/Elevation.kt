package com.example.library.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Elevation tokens — use these for consistent shadow depth.
 */
object Elevation {
    /** 0dp — flat / no shadow */
    val None = 0.dp
    /** 2dp — subtle lift (cards, list items) */
    val Card = 2.dp
    /** 4dp — medium lift (FAB, selected items) */
    val Medium = 4.dp
    /** 8dp — high lift (dialogs, bottom sheets, nav bar) */
    val High = 8.dp
}
