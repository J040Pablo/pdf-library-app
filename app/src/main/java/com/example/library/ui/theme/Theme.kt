/**
 * Main app theme.
 *
 * [darkTheme] is controlled exclusively by [ThemeViewModel] in production.
 * MainActivity resolves the user's saved preference (LIGHT/DARK/SYSTEM) into
 * a Boolean and passes it here — there is no isSystemInDarkTheme() call inside
 * this composable.
 *
 * Previews may pass their own value or rely on the default (false = light).
 */
@Composable
fun LibraryTheme(
    darkTheme: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            // Transparent bars — edge-to-edge is enabled in MainActivity
            window.statusBarColor = android.graphics.Color.TRANSPARENT
            window.navigationBarColor = android.graphics.Color.TRANSPARENT
            window.decorView.setBackgroundColor(colorScheme.background.toArgb())
            WindowCompat.getInsetsController(window, view).apply {
                // Light icons on dark theme, dark icons on light theme
                isAppearanceLightStatusBars = !darkTheme
                isAppearanceLightNavigationBars = !darkTheme
            }
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}